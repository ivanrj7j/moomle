import os
import shutil
from pathlib import Path

from alembic import command
from alembic.config import Config
from alembic.migration import MigrationContext
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected, CommandError
from dotenv import load_dotenv
from sqlalchemy import URL, create_engine, text
from sqlalchemy.orm import Session

appDir = Path(__file__).resolve().parent.parent
migrationsDir = appDir / "migrations"
versionsDir = migrationsDir / "versions"
templatesDir = appDir / "scripts" / "templates"

# 1. Initialize migrations directory from templates inside the container
migrationsDir.mkdir(parents=True, exist_ok=True)
versionsDir.mkdir(parents=True, exist_ok=True)

for filename in ["env.py", "script.py.mako", "README"]:
    src = templatesDir / filename
    dst = migrationsDir / filename
    if src.exists() and not dst.exists():
        shutil.copy(src, dst)

config = Config(str(appDir / "alembic.ini"))
config.set_main_option("script_location", str(migrationsDir))

# 2. Database connection & verification
load_dotenv()
databaseUrl = URL.create(
    drivername="postgresql+psycopg",
    username=os.getenv("POSTGRES_USER"),
    password=os.getenv("POSTGRES_PASSWORD"),
    host=os.getenv("POSTGRES_HOST"),
    port=int(os.getenv("POSTGRES_PORT", "5432")),
    database=os.getenv("POSTGRES_DB"),
)

engine = create_engine(databaseUrl)
script = ScriptDirectory.from_config(config)

with engine.connect() as conn:
    ctx = MigrationContext.configure(conn)
    currentRev = ctx.get_current_revision()

    if currentRev:
        try:
            script.get_revision(currentRev)
        except CommandError:
            print(
                f"[migrate] Warning: Database stamped with revision '{currentRev}', "
                f"which is missing in migrations/versions. Resetting alembic_version table."
            )
            conn.execute(text("DROP TABLE IF EXISTS alembic_version;"))
            conn.commit()

# 3. Apply existing migrations if any exist
heads = script.get_heads()
if heads:
    print(f"[migrate] Applying existing migrations (head: {heads})...")
    command.upgrade(config, "head")

# 4. Check for differences between current database schema and SQLAlchemy models
print("[migrate] Checking for model differences against database...")
try:
    command.check(config)
    print("[migrate] Database schema is up to date.")
except AutogenerateDiffsDetected:
    heads = script.get_heads()
    message = "auto migration" if heads else "initial schema"
    print(f"[migrate] Differences detected. Generating '{message}'...")
    command.revision(
        config,
        message=message,
        autogenerate=True,
    )
    command.upgrade(config, "head")
    print("[migrate] Migration applied successfully.")

# 5. Populate advertisers seed data if table is empty
seedFile = appDir / "adservers_seed.txt"
if seedFile.exists():
    from scripts.seed_advertisers import seedAdvertisers

    with Session(engine) as seedSession:
        hasTable = seedSession.scalar(
            text("SELECT 1 FROM information_schema.tables WHERE table_name = 'advertisers';")
        )
        if hasTable:
            count = seedSession.scalar(text("SELECT count(*) FROM advertisers;"))
            if count == 0:
                print("[migrate] Seeding advertisers table from adservers_seed.txt...")
                seedAdvertisers(seedFile, session=seedSession)
